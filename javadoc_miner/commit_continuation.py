def _javadoc_format_review(grouped: list[dict]) -> list[dict]:
    review: list[dict] = []
    for commit in grouped:
        for change in commit["changes"]:
            for field in ("javadoc_before", "javadoc_after"):
                value = change[field]
                reasons = []
                if "\ufffd" in value:
                    reasons.append("replacement_character")
                if value.strip().startswith("/**") and not value.strip().endswith("*/"):
                    reasons.append("unclosed_javadoc")
                if value.count("<") != value.count(">"):
                    reasons.append("unbalanced_angle_brackets")
                if reasons:
                    review.append(
                        {
                            "project_slug": commit["project_slug"],
                            "commit_hash": commit["commit_hash"],
                            "change_index": change["change_index"],
                            "field": field,
                            "reasons": reasons,
                        }
                    )
    return review



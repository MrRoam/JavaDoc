def _upsert_by_key(path: Path, row: dict, key: str) -> None:
    rows = _read_json(path, [])
    if not isinstance(rows, list):
        rows = []
    rows = [item for item in rows if not isinstance(item, dict) or item.get(key) != row.get(key)]
    rows.append(row)
    _write_json(path, rows)


def _copy_if_exists(source: Path, target: Path, default) -> None:
    if source.exists():
        shutil.copy2(source, target)
    elif isinstance(default, str):
        target.write_text(default, encoding="utf-8")
    else:
        _write_json(target, default)


def _read_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError):
        return default


def _write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(value, ensure_ascii=False, indent=2)
    last_error: OSError | None = None
    for attempt in range(5):
        temp_path = path.with_name(f".{path.name}.{os.getpid()}.{attempt}.tmp")
        try:
            temp_path.write_text(text, encoding="utf-8")
            try:
                temp_path.replace(path)
                return
            except OSError:
                try:
                    if path.exists():
                        path.unlink()
                    temp_path.replace(path)
                    return
                except OSError:
                    path.write_text(text, encoding="utf-8")
                    return
        except OSError as error:
            last_error = error
            try:
                if temp_path.exists():
                    temp_path.unlink()
            except OSError:
                pass
            time.sleep(0.2 * (attempt + 1))
    if last_error is not None:
        raise last_error



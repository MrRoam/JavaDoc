def _remove_failed_repository(continuation_dir: Path, project_slug: str) -> None:
    path = continuation_dir / "failed_repositories.json"
    rows = _read_json(path, [])
    if not isinstance(rows, list):
        return
    rows = [row for row in rows if not isinstance(row, dict) or row.get("project_slug") != project_slug]
    _write_json(path, rows)


def _update_repository_yield_summary(continuation_dir: Path) -> None:
    repos = _read_json(continuation_dir / "scanned_repositories.json", [])
    if not isinstance(repos, list):
        repos = []
    _prune_resolved_failures(continuation_dir, repos)
    progress = _read_json(continuation_dir / "scan_progress.json", [])
    latest_progress: dict[str, dict] = {}
    if isinstance(progress, list):
        for row in progress:
            if isinstance(row, dict) and row.get("project_slug"):
                latest_progress[row["project_slug"]] = row
    rows = []
    for repo in repos:
        latest = latest_progress.get(repo.get("project_slug", ""))
        scanned = int(
            (latest or {}).get("cumulative_commits_scanned", repo.get("scanned_commit_count", 0))
            or 0
        )
        retained = int(
            (latest or {}).get("retained_commits_after_global_dedup", repo.get("retained_commit_count", 0))
            or 0
        )
        retained_changes = int(
            (latest or {}).get("retained_changes_after_global_dedup", repo.get("retained_change_count", 0))
            or 0
        )
        rows.append(
            {
                **repo,
                "scanned_commit_count": scanned,
                "retained_commit_count": retained,
                "retained_change_count": retained_changes,
                "yield_per_1000_scanned_commits": round(retained / scanned * 1000, 4) if scanned else 0,
            }
        )
    _write_json(continuation_dir / "repository_yield_summary.json", rows)
    fields = [
        "project_slug",
        "repository_url",
        "scanned_commit_count",
        "retained_commit_count",
        "retained_change_count",
        "yield_per_1000_scanned_commits",
        "scan_status",
        "stop_reason",
    ]
    _write_csv(continuation_dir / "repository_yield_summary.csv", rows, fields)


def _prune_resolved_failures(continuation_dir: Path, repos: list[dict]) -> None:
    resolved = {
        repo.get("project_slug")
        for repo in repos
        if isinstance(repo, dict) and int(repo.get("scanned_commit_count", 0) or 0) > 0
    }
    if not resolved:
        return
    path = continuation_dir / "failed_repositories.json"
    failures = _read_json(path, [])
    if not isinstance(failures, list):
        return
    failures = [
        failure
        for failure in failures
        if not isinstance(failure, dict) or failure.get("project_slug") not in resolved
    ]
    _write_json(path, failures)



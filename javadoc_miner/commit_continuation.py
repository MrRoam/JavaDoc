def _load_project_counters(checkpoint: dict) -> ProjectCounters:
    value = checkpoint.get("counters", {})
    counters = ProjectCounters()
    if isinstance(value, dict):
        for field in counters.__dict__:
            if field in value:
                setattr(counters, field, value[field])
    return counters


def _should_stop_low_yield(
    counters: ProjectCounters,
    initial_probe_commits: int,
    retained_after_global_dedup: int,
) -> bool:
    if counters.commits_scanned < initial_probe_commits:
        return False
    if counters.commits_scanned == 0:
        return False
    return retained_after_global_dedup / counters.commits_scanned * 1000 < LOW_YIELD_THRESHOLD


def _yield_per_1000(counters: ProjectCounters) -> float:
    if counters.commits_scanned == 0:
        return 0.0
    return round(counters.retained_commits_before_global_dedup / counters.commits_scanned * 1000, 4)


def _retained_new_counts_for_project(grouped: list[dict], slug: str) -> dict[str, int]:
    project_commits = [commit for commit in grouped if commit.get("project_slug") == slug]
    return {
        "commits": len(project_commits),
        "changes": sum(len(commit.get("changes", [])) for commit in project_commits),
    }


def _path_allowed_for_project(project_name: str, path: str) -> bool:
    normalized = path.replace("\\", "/")
    lower = normalized.lower()
    if project_name == "grpc/grpc-java":
        if any(part in lower for part in ("/examples/", "/interop-testing/", "/benchmarks/", "/testing-proto/")):
            return False
        if "generated" in lower or lower.endswith("grpc.java") or lower.endswith("proto.java"):
            return False
    if project_name == "netty/netty":
        allowed = ("buffer/", "codec/", "codec-http/", "codec-http2/", "common/", "handler/", "transport/", "resolver/")
        if not lower.startswith(allowed):
            return False
    if project_name == "apache/avro" and not lower.startswith("lang/java/"):
        return False
    if project_name == "apache/kafka" and not lower.startswith("clients/src/main/java/"):
        return False
    if project_name == "jOOQ/jOOQ" and any(part in lower for part in ("/generated/", "/codegen/", "/meta/")):
        return False
    return True


def _is_generated_source(content: str | None) -> bool:
    if not content:
        return False
    header = "\n".join(content.splitlines()[:40]).lower()
    return any(token in header for token in PRODUCTION_HEADERS)


def _is_metadata_only_commit_message(commit_message: str) -> bool:
    normalized = " ".join(commit_message.lower().split())
    return any(token in normalized for token in METADATA_ONLY_COMMIT_SUBSTRINGS)


def _commit_hashes(repo: GitRepo) -> list[str]:
    return [line for line in repo.run_git(["rev-list", "HEAD"]).splitlines() if line]


def _flatten_grouped(grouped: list[dict], dataset: str) -> list[dict]:
    flat: list[dict] = []
    for commit_index, commit in enumerate(grouped):
        for change in commit.get("changes", []):
            flat.append(
                {
                    "project_slug": commit.get("project_slug", ""),
                    "repository_url": commit.get("repository_url", ""),
                    "commit_hash": commit.get("commit_hash", ""),
                    "issue_summary": commit.get("issue_summary", ""),
                    "change_index": change.get("change_index", 0),
                    "entity_type": change.get("entity_type", ""),
                    "code_before": change.get("code_before", ""),
                    "code_after": change.get("code_after", ""),
                    "javadoc_before": change.get("javadoc_before", ""),
                    "javadoc_after": change.get("javadoc_after", ""),
                    "_dataset": dataset,
                    "_source_order": len(flat),
                    "_source_commit_order": commit_index,
                }
            )
    return flat



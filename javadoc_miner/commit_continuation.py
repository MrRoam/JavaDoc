def mine_commit_continuation_dataset(
    config: CommitContinuationConfig,
    repositories: Iterable[RepositorySpec] | None = None,
) -> dict:
    root_dir = config.root_dir
    baseline_dir = _resolve(root_dir, config.baseline_dir)
    continuation_dir = _resolve(root_dir, config.continuation_dir)
    final_dir = _resolve(root_dir, config.final_dir)
    cache_dir = _resolve(root_dir, config.cache_dir)
    legacy_merged_dir = _resolve(root_dir, config.legacy_merged_dir)
    baseline = _load_grouped_dataset(baseline_dir / "combined_by_commit.json")
    if not baseline:
        raise FileNotFoundError(f"No grouped baseline found in {baseline_dir}")

    specs = _selected_repositories(list(repositories or PRIORITY_REPOSITORIES), config.start_from, config.max_repos)
    completed_existing = _completed_existing_repositories(root_dir)
    baseline_keys = {(item["project_slug"], item["commit_hash"]) for item in baseline}
    _ensure_run_files(continuation_dir)
    current_outputs = refresh_commit_outputs(
        baseline=baseline,
        continuation_dir=continuation_dir,
        final_dir=final_dir,
        baseline_dir=baseline_dir,
        legacy_merged_dir=legacy_merged_dir,
        config=config,
    )

    print("5k commit continuation plan")
    print(f"- baseline grouped commits: {len(baseline)}")
    print(f"- current final commits after existing continuation merge: {current_outputs['summary']['final_commit_count']}")
    print(f"- target final commits: {config.target_commits}")
    print(f"- continuation output: {continuation_dir}")
    print(f"- final output: {final_dir}")
    print("- repositories in order:")
    for spec in specs:
        status = "completed-baseline-skip" if spec.slug in completed_existing and not config.include_completed else "scan"
        print(f"  - {spec.name}: {status}")
    if config.dry_run:
        return current_outputs["summary"]

    for spec in specs:
        if current_outputs["summary"]["final_commit_count"] >= config.target_commits:
            break
        if spec.slug in completed_existing and not config.include_completed:
            _record_skipped_repository(continuation_dir, spec, completed_existing[spec.slug])
            continue
        try:
            _mine_one_project(
                spec=spec,
                config=config,
                cache_dir=cache_dir,
                continuation_dir=continuation_dir,
                baseline_keys=baseline_keys,
                baseline=baseline,
                baseline_dir=baseline_dir,
                legacy_merged_dir=legacy_merged_dir,
                final_dir=final_dir,
            )
            current_outputs = refresh_commit_outputs(
                baseline=baseline,
                continuation_dir=continuation_dir,
                final_dir=final_dir,
                baseline_dir=baseline_dir,
                legacy_merged_dir=legacy_merged_dir,
                config=config,
            )
        except (GitCommandError, OSError) as error:
            _append_json_list(
                continuation_dir / "failed_repositories.json",
                {
                    "project_slug": spec.slug,
                    "repository_url": spec.url,
                    "error": str(error),
                    "failed_at_utc": _utc_now(),
                },
            )
            print(f"Failed {spec.name}: {error}")

    current_outputs = refresh_commit_outputs(
        baseline=baseline,
        continuation_dir=continuation_dir,
        final_dir=final_dir,
        baseline_dir=baseline_dir,
        legacy_merged_dir=legacy_merged_dir,
        config=config,
    )
    return current_outputs["summary"]


def refresh_commit_outputs(
    *,
    baseline: list[dict],
    continuation_dir: Path,
    final_dir: Path,
    baseline_dir: Path,
    legacy_merged_dir: Path,
    config: CommitContinuationConfig,
) -> dict:
    new_raw = _load_all_project_commits(continuation_dir)
    merged = _merge_grouped_commits(baseline, new_raw)
    _write_continuation_top_level(continuation_dir, new_raw, merged)
    _write_final_outputs(final_dir, merged, continuation_dir, baseline_dir, legacy_merged_dir, config)
    return merged


def _mine_one_project(
    *,
    spec: RepositorySpec,
    config: CommitContinuationConfig,
    cache_dir: Path,
    continuation_dir: Path,
    baseline_keys: set[tuple[str, str]],
    baseline: list[dict],
    baseline_dir: Path,
    legacy_merged_dir: Path,
    final_dir: Path,
) -> None:
    print(f"Scanning {spec.name}...")
    repo = GitRepo.clone_or_update(
        spec.url,
        cache_dir,
        force_refresh=config.force_refresh,
        fetch_existing=config.fetch_existing,
    )
    commit_hashes = _commit_hashes(repo)
    if config.smoke_commits:
        commit_hashes = commit_hashes[: config.smoke_commits]
    elif config.max_commits_per_repo is not None:
        commit_hashes = commit_hashes[: config.max_commits_per_repo]

    project_dir = continuation_dir / "per_project" / spec.slug
    project_dir.mkdir(parents=True, exist_ok=True)
    checkpoint = _read_json(project_dir / "checkpoint.json", {})
    processed = set(checkpoint.get("processed_commit_hashes", []))
    retained_commits = _load_grouped_dataset(project_dir / "cleaned_by_commit.json")
    retained_by_hash = {item["commit_hash"]: item for item in retained_commits}
    counters = _load_project_counters(checkpoint)
    batch_start_scanned = counters.commits_scanned
    batch_index = int(checkpoint.get("current_batch", 0) or 0) + 1
    stop_reason = ""
    scan_status = "partial"

    for commit_hash in commit_hashes:
        if commit_hash in processed:
            continue
        if (spec.slug, commit_hash) in baseline_keys and not config.include_completed:
            processed.add(commit_hash)
            counters.commits_scanned += 1
            _save_checkpoint(project_dir, spec, checkpoint, counters, processed, commit_hash, batch_index, "partial", "")
            continue
        counters.commits_scanned += 1
        if not counters.newest_commit:
            counters.newest_commit = commit_hash
        counters.oldest_commit = commit_hash
        commit = _extract_commit_object(repo, spec, commit_hash, counters, project_dir)
        if commit is not None:
            retained_by_hash[commit_hash] = commit
            counters.retained_commits_before_global_dedup = len(retained_by_hash)
            counters.retained_changes_before_global_dedup = sum(len(item["changes"]) for item in retained_by_hash.values())
            counters.method_level_changes = sum(
                1
                for item in retained_by_hash.values()
                for change in item["changes"]
                if change["entity_type"] == "method"
            )
            counters.class_level_changes = sum(
                1
                for item in retained_by_hash.values()
                for change in item["changes"]
                if change["entity_type"] == "class"
            )
            counters.commits_with_multiple_changes = sum(1 for item in retained_by_hash.values() if len(item["changes"]) > 1)
            _write_project_commit_files(project_dir, list(retained_by_hash.values()))

        processed.add(commit_hash)
        _save_checkpoint(project_dir, spec, checkpoint, counters, processed, commit_hash, batch_index, "partial", "")

        scanned_this_batch = counters.commits_scanned - batch_start_scanned
        if scanned_this_batch >= config.batch_size:
            outputs = refresh_commit_outputs(
                baseline=baseline,
                continuation_dir=continuation_dir,
                final_dir=final_dir,
                baseline_dir=baseline_dir,
                legacy_merged_dir=legacy_merged_dir,
                config=config,
            )
            _record_scan_progress(
                continuation_dir,
                spec,
                counters,
                outputs,
                batch_index,
                scanned_this_batch,
                "partial",
                "",
            )
            if outputs["summary"]["final_commit_count"] >= config.target_commits:
                stop_reason = f"target_commits={config.target_commits} reached"
                scan_status = "stopped"
                break
            retained_after = _retained_new_counts_for_project(outputs["grouped"], spec.slug)
            if _should_stop_low_yield(counters, config.initial_probe_commits, retained_after["commits"]):
                stop_reason = "low_yield"
                scan_status = "stopped"
                _append_json_list(
                    continuation_dir / "stopped_low_yield_repositories.json",
                    _repository_yield_row(spec, counters, "stopped", stop_reason, retained_after["commits"], retained_after["changes"]),
                )
                break
            batch_start_scanned = counters.commits_scanned
            batch_index += 1

    else:
        scan_status = "completed" if counters.commits_scanned >= len(commit_hashes) else "partial"
        if config.smoke_commits:
            stop_reason = f"smoke_commits={config.smoke_commits} reached"
        elif config.max_commits_per_repo is not None and counters.commits_scanned >= config.max_commits_per_repo:
            stop_reason = f"max_commits_per_repo={config.max_commits_per_repo} reached"
        else:
            stop_reason = "full_history_scanned" if scan_status == "completed" else "history_incomplete"

    _write_project_commit_files(project_dir, list(retained_by_hash.values()))
    outputs = refresh_commit_outputs(
        baseline=baseline,
        continuation_dir=continuation_dir,
        final_dir=final_dir,
        baseline_dir=baseline_dir,
        legacy_merged_dir=legacy_merged_dir,
        config=config,
    )
    final_batch_size = max(0, counters.commits_scanned - batch_start_scanned)
    if final_batch_size or not _read_json(continuation_dir / "scan_progress.json", []):
        _record_scan_progress(
            continuation_dir,
            spec,
            counters,
            outputs,
            batch_index,
            final_batch_size,
            scan_status,
            stop_reason,
        )
    _save_checkpoint(project_dir, spec, checkpoint, counters, processed, checkpoint.get("last_processed_commit", ""), batch_index, scan_status, stop_reason)
    _update_repository_yield_summary(continuation_dir)
    print(
        f"{spec.name}: scanned={counters.commits_scanned}, "
        f"retained_commits_before_global_dedup={counters.retained_commits_before_global_dedup}, "
        f"yield={_yield_per_1000(counters):.2f}, status={scan_status}, stop_reason={stop_reason}"
    )


def _extract_commit_object(
    repo: GitRepo,
    spec: RepositorySpec,
    commit_hash: str,
    counters: ProjectCounters,
    project_dir: Path,
) -> dict | None:
    try:
        changed_paths = parse_changed_paths(repo.show_name_status(commit_hash))
    except GitCommandError:
        return None
    if not changed_paths:
        return None
    try:
        commit_message = repo.commit_message(commit_hash)
    except GitCommandError:
        return None
    if is_low_signal_commit_message(commit_message):
        counters.weak_issue_detected += 1
        counters.weak_issue_unresolved += 1
        _append_json_list(
            project_dir / "unresolved_issue_summary.json",
            {
                "commit_hash": commit_hash,
                "issue_summary": commit_message.splitlines()[0] if commit_message else "",
                "reason": "low_signal_commit_message",
            },
        )
        return None
    if _is_metadata_only_commit_message(commit_message):
        counters.format_only_rejection_count += 1
        return None
    try:
        patch = repo.show_commit_patch(commit_hash)
    except GitCommandError:
        return None
    if not commit_has_javadoc_changes(patch):
        return None
    if not commit_has_javadoc_and_code_changes(patch):
        return None
    try:
        file_changes = extract_file_changes(repo, commit_hash, changed_paths)
    except GitCommandError:
        return None

    issues = find_issues(commit_message)
    pending: list[PendingOutputSample] = []
    for file_change in file_changes:
        if not _path_allowed_for_project(spec.name, file_change.path):
            continue
        if _is_generated_source(file_change.old_content) or _is_generated_source(file_change.new_content):
            continue
        try:
            old_entities = parse_entities(file_change.old_content or "")
            new_entities = parse_entities(file_change.new_content or "")
            counters.java_parse_success_count += 1
        except Exception as error:  # pragma: no cover - defensive against parser edge cases
            counters.java_parse_failure_count += 1
            _append_json_list(
                project_dir / "invalid_changes.json",
                {
                    "commit_hash": commit_hash,
                    "file_path": file_change.path,
                    "reason": f"java_parse_failure:{error}",
                },
            )
            continue
        for old_entity, new_entity, classification in _classify_file_entities(old_entities, new_entities, file_change):
            pending.append(
                PendingOutputSample(
                    commit_hash=commit_hash,
                    commit_message=commit_message,
                    issue_ids=issues,
                    file_change=file_change,
                    old_entity=old_entity,
                    new_entity=new_entity,
                    classification=classification,
                )
            )
    if not pending:
        return None
    counters.raw_candidate_commits += 1
    counters.raw_candidate_changes += len(pending)

    issue_summary, fallback_applied = commit_summary_with_fallback(commit_message)
    if is_weak_issue_summary(issue_summary):
        counters.weak_issue_detected += 1
        counters.weak_issue_unresolved += 1
        _append_json_list(
            project_dir / "unresolved_issue_summary.json",
            {
                "commit_hash": commit_hash,
                "issue_summary": issue_summary,
                "detected": True,
                "resolved": False,
                "resolution_source": "",
                "reason": "weak_issue_summary_unresolved",
            },
        )
        return None
    if fallback_applied:
        counters.weak_issue_detected += 1
        counters.weak_issue_resolved += 1

    samples: list[OutputSample] = []
    for candidate in _deduplicate_samples(pending):
        issue_id = candidate.issue_ids[0] if candidate.issue_ids else ""
        try:
            sample = _build_output_sample(
                repo=repo,
                commit_hash=commit_hash,
                commit_message=commit_message,
                issue_id=issue_id,
                issue_summary=issue_summary,
                file_change=candidate.file_change,
                old_entity=candidate.old_entity,
                new_entity=candidate.new_entity,
                classification=candidate.classification,
                issue_summary_fallback_applied=fallback_applied,
            )
        except ValueError:
            continue
        validation = validate_output_sample(sample)
        if validation.disposition == "retain":
            samples.append(sample)
        elif validation.disposition == "review":
            counters.moved_to_review += 1
            _append_json_list(
                project_dir / "entity_type_review.json",
                {"commit_hash": commit_hash, "reason": validation.reason, "file_path": sample.file_path},
            )
        else:
            counters.invalid_changes += 1
            _append_json_list(
                project_dir / "invalid_changes.json",
                {"commit_hash": commit_hash, "reason": validation.reason, "file_path": sample.file_path},
            )
    if not samples:
        return None
    return {
        "project_slug": spec.slug,
        "repository_url": spec.url,
        "commit_hash": commit_hash,
        "issue_summary": issue_summary,
        "changes": [
            {
                "change_index": index,
                "entity_type": sample.entity_type,
                "code_before": sample.code_before,
                "code_after": sample.code_after,
                "javadoc_before": sample.javadoc_before,
                "javadoc_after": sample.javadoc_after,
            }
            for index, sample in enumerate(samples, start=1)
        ],
    }


def _merge_grouped_commits(baseline: list[dict], new_commits: list[dict]) -> dict:
    raw_flat = _flatten_grouped(baseline, "baseline") + _flatten_grouped(new_commits, "new")
    cleaned: list[dict] = []
    removed_format_only: list[dict] = []
    invalid_changes: list[dict] = []
    entity_type_review: list[dict] = []
    unresolved_issue_summary: list[dict] = []
    for change in raw_flat:
        clean, reason = _clean_flat_change(change)
        if clean is None:
            target = entity_type_review if reason == "unknown_entity_type" else invalid_changes
            target.append(_audit_removed_change(change, reason))
            continue
        format_reason = format_only_reason(clean["javadoc_before"], clean["javadoc_after"])
        if format_reason:
            removed_format_only.append(_audit_removed_change(clean, format_reason))
            continue
        cleaned.append(clean)

    seen: dict[str, dict] = {}
    deduped: list[dict] = []
    removed_duplicates: list[dict] = []
    for change in cleaned:
        fingerprint = content_fingerprint(change)
        if fingerprint in seen:
            removed_duplicates.append(
                {
                    **_audit_removed_change(change, "duplicate_change"),
                    "duplicate_of": _change_ref(seen[fingerprint]),
                }
            )
            continue
        seen[fingerprint] = change
        deduped.append(change)

    grouped, issue_conflicts, empty_commits = _group_flat_changes(deduped, raw_flat, unresolved_issue_summary)
    validation = validate_grouped_dataset(grouped)
    summary = _build_5k_summary(
        baseline=baseline,
        new_commits=new_commits,
        raw_flat=raw_flat,
        cleaned_flat=deduped,
        grouped=grouped,
        removed_duplicates=removed_duplicates,
        removed_format_only=removed_format_only,
        unresolved_issue_summary=unresolved_issue_summary,
        entity_type_review=entity_type_review,
        invalid_changes=invalid_changes,
        validation=validation,
        empty_commits=empty_commits,
    )
    return {
        "raw_flat": raw_flat,
        "cleaned_flat": _strip_flat_internal(deduped),
        "grouped": grouped,
        "removed_duplicates": removed_duplicates,
        "removed_empty_commits": empty_commits,
        "removed_format_only": removed_format_only,
        "unresolved_issue_summary": unresolved_issue_summary,
        "entity_type_review": entity_type_review,
        "invalid_changes": invalid_changes,
        "javadoc_format_review": _javadoc_format_review(grouped),
        "issue_summary_conflicts": issue_conflicts,
        "validation": validation,
        "summary": summary,
    }


def _clean_flat_change(change: dict) -> tuple[dict | None, str]:
    required = ("project_slug", "repository_url", "commit_hash", "issue_summary", *CHANGE_FIELDS)
    if not all(field in change for field in required):
        return None, "missing_fields"
    clean = dict(change)
    for field in ("project_slug", "repository_url", "commit_hash", "issue_summary", *CHANGE_FIELDS):
        if field == "change_index":
            continue
        value = clean[field]
        if not isinstance(value, str):
            return None, "non_string_field"
        value = normalize_file_text(value)
        if not value.strip():
            return None, "empty_field"
        clean[field] = value
    if clean["entity_type"] not in {"method", "class"}:
        return None, "unknown_entity_type"
    if clean["code_before"] == clean["code_after"]:
        return None, "identical_code"
    if clean["javadoc_before"] == clean["javadoc_after"]:
        return None, "identical_javadoc"
    before_reason = validate_code_snippet(clean["code_before"], clean["entity_type"])
    after_reason = validate_code_snippet(clean["code_after"], clean["entity_type"])
    if before_reason or after_reason:
        return None, f"invalid_code:{before_reason or after_reason}"
    return clean, ""


def _group_flat_changes(
    changes: list[dict],
    raw_flat: list[dict],
    unresolved_issue_summary: list[dict],
) -> tuple[list[dict], list[dict], list[dict]]:
    raw_commit_keys = OrderedDict(((item["project_slug"], item["commit_hash"]), item) for item in raw_flat)
    by_commit: OrderedDict[tuple[str, str], list[dict]] = OrderedDict()
    for change in changes:
        by_commit.setdefault((change["project_slug"], change["commit_hash"]), []).append(change)
    grouped: list[dict] = []
    issue_conflicts: list[dict] = []
    for (project_slug, commit_hash), group in by_commit.items():
        summaries = [item["issue_summary"] for item in group]
        good_summaries = [summary for summary in summaries if not is_weak_issue_summary(summary)]
        if not good_summaries:
            first = group[0]
            unresolved_issue_summary.append(
                {
                    "project_slug": project_slug,
                    "repository_url": first["repository_url"],
                    "commit_hash": commit_hash,
                    "issue_summary": summaries[0] if summaries else "",
                    "detected": True,
                    "resolved": False,
                    "resolution_source": "",
                    "reason": "weak_issue_summary_unresolved",
                }
            )
            continue
        chosen_summary = good_summaries[0]
        if len(set(summaries)) > 1:
            issue_conflicts.append(
                {
                    "project_slug": project_slug,
                    "commit_hash": commit_hash,
                    "chosen_issue_summary": chosen_summary,
                    "candidate_issue_summaries": sorted(set(summaries)),
                }
            )
        commit = {
            "project_slug": project_slug,
            "repository_url": group[0]["repository_url"],
            "commit_hash": commit_hash,
            "issue_summary": chosen_summary,
            "changes": [],
        }
        for change in group:
            commit["changes"].append(
                {
                    "change_index": len(commit["changes"]) + 1,
                    "entity_type": change["entity_type"],
                    "code_before": change["code_before"],
                    "code_after": change["code_after"],
                    "javadoc_before": change["javadoc_before"],
                    "javadoc_after": change["javadoc_after"],
                }
            )
        grouped.append(commit)

    grouped_keys = {(item["project_slug"], item["commit_hash"]) for item in grouped}
    empty_commits = [
        {
            "project_slug": key[0],
            "repository_url": raw_commit_keys[key].get("repository_url", ""),
            "commit_hash": key[1],
            "removal_reason": "all_changes_removed",
        }
        for key in raw_commit_keys
        if key not in grouped_keys
    ]
    return grouped, issue_conflicts, empty_commits


def _build_5k_summary(
    *,
    baseline: list[dict],
    new_commits: list[dict],
    raw_flat: list[dict],
    cleaned_flat: list[dict],
    grouped: list[dict],
    removed_duplicates: list[dict],
    removed_format_only: list[dict],
    unresolved_issue_summary: list[dict],
    entity_type_review: list[dict],
    invalid_changes: list[dict],
    validation: dict,
    empty_commits: list[dict],
) -> dict:
    change_counts = [len(commit["changes"]) for commit in grouped]
    method_count = sum(1 for commit in grouped for change in commit["changes"] if change["entity_type"] == "method")
    class_count = sum(1 for commit in grouped for change in commit["changes"] if change["entity_type"] == "class")
    per_project_commits = Counter(commit["project_slug"] for commit in grouped)
    per_project_changes = Counter()
    for commit in grouped:
        per_project_changes[commit["project_slug"]] += len(commit["changes"])
    return {
        "baseline_path": "final_dataset_merged_no_commit_cap",
        "baseline_commit_count": len(baseline),
        "baseline_change_count": sum(len(commit.get("changes", [])) for commit in baseline),
        "new_raw_candidate_commit_count": len(new_commits),
        "new_raw_candidate_change_count": sum(len(commit.get("changes", [])) for commit in new_commits),
        "combined_raw_change_count": len(raw_flat),
        "combined_cleaned_change_count": len(cleaned_flat),
        "duplicate_change_count": len(removed_duplicates),
        "empty_commit_removed_count": len(empty_commits),
        "format_only_removed_count": len(removed_format_only),
        "weak_issue_unresolved_count": len(unresolved_issue_summary),
        "entity_type_review_count": len(entity_type_review),
        "invalid_change_count": len(invalid_changes),
        "final_commit_count": len(grouped),
        "final_total_change_count": sum(change_counts),
        "final_method_change_count": method_count,
        "final_class_change_count": class_count,
        "commits_with_one_change": sum(1 for count in change_counts if count == 1),
        "commits_with_multiple_changes": sum(1 for count in change_counts if count > 1),
        "average_changes_per_commit": round(sum(change_counts) / len(change_counts), 4) if change_counts else 0,
        "median_changes_per_commit": median(change_counts) if change_counts else 0,
        "max_changes_in_one_commit": max(change_counts, default=0),
        "per_project_commit_count": dict(sorted(per_project_commits.items())),
        "per_project_change_count": dict(sorted(per_project_changes.items())),
        "validation": validation,
    }



def _write_source_backups(final_dir: Path, baseline_dir: Path, legacy_merged_dir: Path, continuation_dir: Path) -> None:
    backup_root = final_dir / "source_backups"
    backup_root.mkdir(parents=True, exist_ok=True)
    for source_dir in (legacy_merged_dir, baseline_dir, continuation_dir):
        if not source_dir.exists():
            continue
        target = backup_root / source_dir.name
        target.mkdir(parents=True, exist_ok=True)
        for file_name in (
            "combined_by_commit.json",
            "combined_cleaned_flat.json",
            "summary.json",
            "summary.csv",
            "validation_report.json",
            "README.md",
            "cleaned_by_commit.json",
            "raw_candidates_by_commit.json",
            "scan_progress.json",
            "repository_yield_summary.json",
        ):
            source = source_dir / file_name
            if source.exists():
                try:
                    shutil.copy2(source, target / file_name)
                except OSError as error:
                    _append_json_list(
                        backup_root / "backup_warnings.json",
                        {
                            "source": str(source),
                            "target": str(target / file_name),
                            "reason": str(error),
                        },
                    )
    _write_json(backup_root / "scan_repository_order.json", [_spec_dict(spec) for spec in PRIORITY_REPOSITORIES])
    _write_json(backup_root / "run_config.json", _config_dict_for_json())
    try:
        import subprocess

        result = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=Path(__file__).resolve().parents[1],
            text=True,
            capture_output=True,
            check=False,
        )
        if result.returncode == 0:
            (backup_root / "code_git_commit.txt").write_text(result.stdout.strip() + "\n", encoding="utf-8")
    except OSError:
        pass



def _selected_repositories(
    repositories: list[RepositorySpec],
    start_from: str,
    max_repos: int | None,
) -> list[RepositorySpec]:
    if start_from:
        start_slug = repository_slug(start_from)
        start_index = next(
            (
                index
                for index, spec in enumerate(repositories)
                if start_from in {spec.name, spec.slug} or start_slug == spec.slug
            ),
            None,
        )
        if start_index is None:
            raise ValueError(f"Unknown start repository: {start_from}")
        repositories = repositories[start_index:]
    if max_repos is not None:
        repositories = repositories[:max_repos]
    return repositories


